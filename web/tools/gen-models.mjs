// Cada pieza: s=forma (box, win=caja con ventanas, cyl, cone, sphere, roof=tejado a dos aguas, gem), p=centro, z=tamaño,
// c=color, r=giro en grados, spin/spinZ=gira sin parar. La unidad es una casilla. Uso: node web/tools/gen-models.mjs
import fs from 'node:fs';

const make = (fn) => { const P = []; fn({
  // Las alturas se dan desde el suelo (y = base) para no calcular centros a mano.
  box: (x, y, z, w, h, d, c, r) => P.push({ s: 'box', p: [x, y + h / 2, z], z: [w, h, d], c, ...(r && { r }) }),
  win: (x, y, z, w, h, d, c) => P.push({ s: 'win', p: [x, y + h / 2, z], z: [w, h, d], c }),
  cyl: (x, y, z, dia, h, c, r) => P.push({ s: 'cyl', p: [x, y + h / 2, z], z: [dia, h, dia], c, ...(r && { r }) }),
  cone: (x, y, z, dia, h, c) => P.push({ s: 'cone', p: [x, y + h / 2, z], z: [dia, h, dia], c }),
  sph: (x, y, z, dx, dy, dz, c) => P.push({ s: 'sphere', p: [x, y, z], z: [dx, dy ?? dx, dz ?? dx], c }),
  roof: (x, y, z, w, h, d, c, r) => P.push({ s: 'roof', p: [x, y + h / 2, z], z: [w, h, d], c, ...(r && { r }) }),
  gem: (x, y, z, w, h, d, c, spin) => P.push({ s: 'gem', p: [x, y, z], z: [w, h, d], c, ...(spin && { spin: 1 }) }),
  spinDisc: (x, y, z, dia, h, c) => P.push({ s: 'cyl', p: [x, y, z], z: [dia, h, dia], c, r: [90, 0, 0], spin: 1 }),
  blade: (x, y, z, w, h, d, c, angle) => P.push({ s: 'box', p: [x, y, z], z: [w, h, d], c, r: [0, 0, angle], spinZ: 1 }),
}); return P; };

